# 예상 3: p-value = 0.2이면 H0가 참이라고 확정할 수 있는가?

# 4. 직접 실행 ----------------------------------------------------
# 실험 A: 서로 다른 두 집단의 평균 연비를 비교한다.
# am은 변속기 구분이다(0 = 자동, 1 = 수동). 두 집단은 대응표본이 아니다.
# H0: 두 모집단의 평균 연비가 같다. H1: 두 평균 연비가 다르다.
# mpg ~ am은 mpg를 am으로 나눈 두 집단에서 비교한다는 표현이다.
# 기본 t.test()는 두 집단 분산이 같다고 가정하지 않는 Welch t-test이다.
mean_test <- t.test(mpg ~ am, data = mtcars, alternative = "two.sided")
cat("두 집단 평균 연비의 t 검정:\n")
print(mean_test)
# sample estimates에서 group 0 약 17.15, group 1 약 24.39를 읽는다.
# t 약 -3.77의 음수는 자동 평균이 수동 평균보다 낮다는 방향을 나타낸다.
# p-value 약 0.00137 < 0.05이므로 평균이 같다는 H0를 기각한다.
# 작은 p-value가 차이의 크기를 나타내지는 않는다. 평균 차이도 함께 읽는다.
# mtcars는 실습 자료이다. 이 결과만으로 변속기가 연비 차이의 원인이라고
# 확정하거나 모든 자동차에 일반화하지 않는다.

# 실험 B: 두 범주형 변수의 관계를 도수표로 검정한다.
# 가상의 실습 집단(A/B)과 결과(통과/미통과)를 사용한다.
# H0: 집단과 결과는 독립이다. H1: 집단과 결과는 독립이 아니다.
# chisq.test()에는 여기서 평균이나 백분율 대신 관측 도수를 넣는다.
counts <- matrix(c(30, 10, 10, 30), nrow = 2, byrow = TRUE,
                 dimnames = list(group = c("A", "B"),
                                 result = c("통과", "미통과")))
cat("관측 도수:\n")
print(counts)
category_test <- chisq.test(counts)
cat("카이제곱 독립성 검정:\n")
print(category_test)
cat("H0 아래의 기대도수:\n")
print(category_test$expected)
# 독립이라면 각 칸의 기대도수가 20이다. 관측된 30/10과 비교한다.
# X-squared는 관측도수가 기대도수에서 벗어난 정도를 요약하며 음수가 아니다.
# 기본 2 × 2 표 검정은 연속성 보정을 사용하여 X-squared = 18.05이다.
# p-value < 0.05이므로 독립이라는 H0를 기각한다. 평균 차이 검정이 아니다.
# 기대도수가 충분한 예제를 사용했다. 기대도수가 너무 작으면 카이제곱 근사에 주의한다.
# 집단과 결과의 관련성이 곧 집단의 인과적 효과를 증명하는 것은 아니다.

# 실험 C: 같은 두 집단을 원래 값 대신 순위에 기반해 비교한다.
# wilcox.test()의 두 독립 집단 비교는 Wilcoxon 순위합 검정이다.
# t-test는 평균을 비교하고, 이 비모수 검정은 순위를 이용한다.
# 비모수는 '아무 가정도 없다'는 뜻이 아니다. 관측의 독립성은 여전히 필요하다.
# 여기서는 두 분포가 같은 모양에서 위치만 달라질 수 있다고 가정한다.
# H0: 두 분포의 위치 차이 = 0. H1: 두 분포의 위치 차이 != 0.
# 분포 모양이 다르면 결과를 단순히 중앙값 차이로 해석하지 않는다.
# mpg에 같은 값이 있으므로 exact = FALSE로 근사 p-value를 구한다.
rank_test <- wilcox.test(mpg ~ am, data = mtcars,
                         alternative = "two.sided", exact = FALSE)
cat("두 집단 연비의 Wilcoxon 순위합 검정:\n")
print(rank_test)
# W는 순위에 기반한 검정통계량이다. 평균 차이나 mpg 단위의 변화량이 아니다.
# 이 출력에서도 결론은 p-value와 alpha의 비교로 내린다.
print(c(p_value = rank_test$p.value, alpha = alpha))
# p-value < 0.05이므로 위 가정 아래 위치 차이가 0이라는 H0를 기각한다.
# 이 예제에서 두 검정의 결론이 같아도 t-test와 Wilcoxon의 의미가 같은 것은 아니다.

# 5. 결과 해석 ----------------------------------------------------
# 읽을 순서: 검정할 문제와 H0/H1 → 검정통계량(t, X-squared, W) → p-value → 결론.
# reject H0(기각): 정한 유의수준에서 H0에 반하는 통계적 근거가 있다.
# fail to reject H0(기각하지 못함): H0를 기각할 근거가 충분하지 않다.
# '기각하지 못함'을 'H0 채택/참으로 증명'이라고 바꾸어 말하지 않는다.
# 함수 선택: 평균 비교는 t.test(), 범주형 도수의 독립성은 chisq.test(),
# 두 독립 집단의 순위 기반 위치 비교는 wilcox.test()를 사용했다.

# 6. 하나 바꿔보기 ------------------------------------------------
# 데이터와 t 검정 결과는 두고 alpha만 0.05에서 0.001로 바꿔 비교한다.
# 예상: 약 0.00137인 p-value는 새 기준보다 작은가? 기각 여부가 바뀌는가?
stricter_alpha <- 0.001
print(data.frame(
  p_value = mean_test$p.value,
  reject_at_0.05 = mean_test$p.value < alpha,
  reject_at_0.001 = mean_test$p.value < stricter_alpha
))
# 0.05에서는 TRUE로 기각, 더 엄격한 0.001에서는 FALSE로 기각하지 못함이다.
# p-value는 변하지 않는다. 판단 기준이 달라져 결론이 달라진다.
# 이 비교는 학습용이다. 실제 검정에서 결과를 본 뒤 유리한 alpha를 고르지 않는다.

