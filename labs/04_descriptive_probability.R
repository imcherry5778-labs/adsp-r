# 1. 목표 --------------------------------------------------------
# - 평균·중앙값으로 중심을, 분산·표준편차로 산포를 해석한다.
# - 상관계수의 부호와 크기를 읽고 인과관계와 구분한다.
# - 정규분포의 누적확률과 이항분포의 특정 횟수 확률을 구분한다.

# 2. 핵심 개념과 작은 예제 ----------------------------------------
# 중심은 값들이 어디에 모여 있는지, 산포는 얼마나 퍼져 있는지를 뜻한다.
# 평균은 합을 개수로 나눈 값, 중앙값은 정렬했을 때 가운데 위치의 값이다.
# mpg는 연비(miles per gallon)이며 값이 클수록 같은 연료로 멀리 간다.
small_mpg <- mtcars$mpg[1:3]
print(small_mpg)
print(c(mean = mean(small_mpg), median = median(small_mpg)))
# 21, 21, 22.8의 평균은 21.6, 중앙값은 21이다. 두 중심이 같을 필요는 없다.

# 분산은 평균에서 떨어진 정도를 제곱해 요약한다. var()는 표본분산이다.
# 표본분산은 제곱한 편차의 합을 n - 1로 나눈다. 여기서는 분모가 2이다.
# 표준편차는 분산의 양의 제곱근으로, 원래 변수와 단위가 같다.
print(c(variance = var(small_mpg), sd = sd(small_mpg)))
# 분산 1.08의 단위는 mpg의 제곱, 표준편차 약 1.04의 단위는 mpg이다.
# 따라서 분산과 표준편차의 숫자 크기를 같은 단위처럼 비교하지 않는다.

# 3. 먼저 예상하기 -----------------------------------------------
# 예상 1: mtcars의 모든 연비가 두 배가 되면 평균·표준편차·분산은
#         각각 두 배인가, 네 배인가? 6절에서 직접 비교한다.
# 예상 2: 차가 무거울수록 연비가 낮아지는 패턴이라면 상관계수의 부호는?
# 예상 3: 표준정규분포에서 0 이하일 확률은 0.5보다 작을까, 같을까?
#         성공확률 0.5인 독립 시행 4번에서 정확히 2번 성공할 확률은
#         '2번 이하 성공할 확률'과 같은가?

# 4. 직접 실행 ----------------------------------------------------
# 실험 A: 전체 연비의 중심과 산포를 나누어 읽는다.
mpg <- mtcars$mpg
mpg_stats <- c(mean = mean(mpg), median = median(mpg),
               variance = var(mpg), sd = sd(mpg))
cat("연비의 중심과 산포:\n")
print(mpg_stats)
cat("연비의 최솟값, 사분위수, 최댓값:\n")
print(quantile(mpg, probs = c(0, 0.25, 0.5, 0.75, 1)))
# mean 약 20.09와 median 19.2는 중심, sd 약 6.03은 퍼짐의 크기이다.
# variance 약 36.32가 크다고 평균 연비가 높다는 뜻은 아니다.
# quantile()의 50%는 중앙값, 25%와 75%는 각각 Q1과 Q3이다.

# 같은 자료를 두 그림으로 본다. 하나씩 실행하고 Plots에서 확인하세요.
hist(mpg, breaks = 6, main = "mtcars: mpg", xlab = "mpg", ylab = "Frequency")
# 가로축은 연비 구간, 세로축은 그 구간에 들어간 자동차 수이다.
# 막대가 높은 구간은 연비 자체가 높다는 뜻이 아니라 관측이 많다는 뜻이다.
boxplot(mpg, main = "mtcars: mpg", ylab = "mpg")
# 상자 안의 선에서 중앙값, 상자와 수염에서 퍼짐을 확인한다.
# 상자그림의 경첩(hinge)은 Q1/Q3에 대응하지만 quantile()과 약간 다를 수 있다.
# 수염 끝은 1.5 × IQR 경계 안의 실제 관측값이며 항상 최솟값·최댓값은 아니다.

# 실험 B: 연비와 무게의 선형 관계를 숫자로 요약한다.
# wt는 무게(1,000 pounds)이다. cor()의 기본값은 Pearson 상관계수이다.
# 계수는 -1부터 1 사이이다. 부호는 방향, 절댓값은 선형 관계의 강도를 나타낸다.
cat("연비와 무게의 상관계수:\n")
print(cor(mtcars$mpg, mtcars$wt))
# 약 -0.87: 무게가 클수록 연비가 낮아지는 강한 음의 선형 관계가 관찰된다.
# -0.87을 '무게 1 증가 시 연비 0.87 감소'로 읽지 않는다. 변화량 계수가 아니다.
# 이 자료의 상관관계만으로 무게가 연비 변화의 원인이라고 확정할 수 없다.
# 다른 변수의 영향도 있을 수 있다. 상관관계와 인과관계를 구분한다.

# 실험 C: 분포와 사건을 먼저 정한 뒤 확률을 계산한다.
# Z가 평균 0, 표준편차 1인 표준정규분포를 따른다고 가정한다.
# pnorm(q)는 기본적으로 P(Z <= q), 즉 q까지의 누적확률을 반환한다.
cat("표준정규분포에서 0 이하, 1.96 이하일 확률:\n")
print(c(P_Z_le_0 = pnorm(0), P_Z_le_1.96 = pnorm(1.96)))
# 0.5는 전체 확률의 절반이 0 이하라는 뜻이다.
# 약 0.975는 1.96 이하일 확률이다. '정확히 1.96일 확률'이 아니다.
# 연속분포에서 한 점의 확률은 0이다. pnorm()은 그 점까지의 면적을 구한다.

# X는 성공확률이 일정한 독립 시행 4번에서 성공한 횟수라고 가정한다.
# dbinom(x, size, prob)는 이항분포에서 P(X = x)를 반환한다.
cat("4번 중 정확히 2번 성공할 확률:\n")
print(dbinom(2, size = 4, prob = 0.5))
# 0.375, 즉 37.5%이다. 0·1번 성공까지 더한 '2번 이하'의 확률이 아니다.
# 두 확률 예제는 분포 가정 아래의 계산이며 mtcars에 분포를 적합한 결과가 아니다.

# 5. 결과 해석 ----------------------------------------------------
# 기술통계: mean/median → 중심, variance/sd → 산포, quantile → 위치를 읽는다.
# 상관계수: 부호 → 방향, 절댓값 → 선형 관계의 강도, 인과 해석 가능 여부를 읽는다.
# 확률: 분포와 사건 → 반환값 → 비율(또는 백분율) 순서로 해석한다.
# 같은 0~1 사이 숫자여도 확률과 상관계수는 의미가 다르다.

# 6. 하나 바꿔보기 ------------------------------------------------
# 원자료의 모양은 유지하고 모든 연비 값만 두 배로 바꾼다.
scaled_mpg <- 2 * mpg
cat("값을 두 배로 바꾼 뒤 / 바꾸기 전의 비율:\n")
print(c(mean_ratio = mean(scaled_mpg) / mean(mpg),
        sd_ratio = sd(scaled_mpg) / sd(mpg),
        variance_ratio = var(scaled_mpg) / var(mpg)))
# 평균과 표준편차는 두 배, 분산은 네 배이다. 분산은 편차를 제곱하기 때문이다.

