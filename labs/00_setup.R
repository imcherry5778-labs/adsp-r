# 1. 목표 --------------------------------------------------------
# - Console과 스크립트의 역할을 구분한다.
# - 값을 객체에 저장하고, 객체를 사용해 계산한다.
# - R 버전과 sessionInfo()에서 현재 실행 환경을 확인한다.

# 2. 핵심 개념과 작은 예제 ----------------------------------------
# Console은 명령을 실행하고 결과를 확인하는 곳이다.
# 스크립트는 다시 실행할 코드를 적어 두는 곳이다.
# 코드를 적기만 하면 계산되지 않는다. 해당 줄을 실행해야 한다.

# 산술식 2 + 3의 결과는 5이다. print()는 값을 명시적으로 출력한다.
print(2 + 3)

# <-는 오른쪽 값을 왼쪽 이름의 객체에 저장한다.
# 아래 첫 줄은 저장하고, 둘째 줄은 저장된 값을 보여 준다.
unit_price <- 1000
print(unit_price)

# 3. 먼저 예상하기 -----------------------------------------------
# 단가 unit_price가 1000일 때 수량 3의 총액을 total에 저장한다.
# 그 뒤 unit_price만 1200으로 바꾸고 total은 다시 계산하지 않는다.
# 예상 1: total을 출력하면 3000인가, 3600인가?
# 예상 2: total을 다시 계산하면 값이 얼마가 되는가?
# 예상 값을 정한 뒤 다음 코드를 실행하세요.

# 4. 직접 실행 ----------------------------------------------------
# 총액을 계산해 저장한다.
quantity <- 3
total <- unit_price * quantity

# 단가만 바꾼다. 객체에 저장된 값이 어떻게 달라지는지 확인한다.
unit_price <- 1200
cat("단가를 바꾼 직후 total:\n")
print(total)
cat("현재 unit_price:\n")
print(unit_price)

# 바뀐 단가를 반영하려면 계산한 값을 다시 저장해야 한다.
total <- unit_price * quantity
cat("다시 계산한 total:\n")
print(total)

# 실행 환경도 확인한다. 데이터나 계산 결과를 요약하는 명령은 아니다.
print(R.version.string)
sessionInfo()

# 5. 결과 해석 ----------------------------------------------------
# - 첫 total은 3000이다. total에는 계산 당시의 값이 저장되어 있다.
# - unit_price는 1200이지만, 이 변경만으로 total이 자동 갱신되지는 않는다.
# - 다시 계산한 total은 3600이다. <-를 다시 실행해 값을 덮어썼기 때문이다.
# R 객체를 읽을 때는 이름뿐 아니라 어떤 줄을 실행해 값을 저장했는지 본다.
# 위 코드를 순서대로 다시 실행하면 처음 단가 1000부터 실험을 재현할 수 있다.

# sessionInfo() 출력에서는 다음 항목을 찾으세요.
# - R version: 현재 사용하는 R의 버전. R.version.string과 비교한다.
# - Platform / Running under: R이 실행되는 플랫폼과 운영체제.
# - attached base packages: 현재 붙어 있는 기본 패키지.
# 숫자나 항목은 실행 환경에 따라 달라질 수 있다.
# 이 출력은 실행 환경의 기록이며, 객체 total의 값이나 분석 결론은 아니다.

# 6. 하나 바꿔보기 ------------------------------------------------
# 단가 1200은 유지하고 수량만 3에서 5로 바꾼다.
# 실행 전 예상: 다시 계산한 총액은 3600보다 얼마나 증가하는가?
quantity <- 5
total <- unit_price * quantity
cat("수량을 5로 바꿔 다시 계산한 total:\n")
print(total)
# 6000으로 2400 증가한다. 수량을 저장하고 총액 계산도 다시 실행했다.

