# 2. 핵심 개념과 작은 예제 ----------------------------------------
# H0(귀무가설)는 검정의 기준이 되는 주장, H1(대립가설)은 그에 맞서는 주장이다.
# 유의수준 alpha는 검정 전에 정한다. 여기서는 0.05를 사용한다.
# alpha는 H0가 참일 때 잘못 기각하는 오류를 허용하는 기준 수준이다.
# p-value는 H0가 참이라는 가정 아래, 관측한 검정통계량만큼 또는 그보다
# 더 극단적인 결과가 나올 확률이다. H0가 참일 확률이 아니다.
# p-value < alpha이면 H0 기각, 그렇지 않으면 H0를 기각하지 못한다.
alpha <- 0.05

# 작은 예제: 연비의 모집단 평균이 학습용 기준 20과 다른가?
# H0: 모집단 평균 연비 = 20. H1: 모집단 평균 연비 != 20(양측검정).
# 표본평균을 비교하는 모수 검정인 일표본 t-test를 사용한다.
# t 검정은 관측의 독립성과 모집단의 정규성 등 가정 아래 해석한다.
one_sample <- t.test(mtcars$mpg, mu = 20, alternative = "two.sided")
print(one_sample)
# t 약 0.085는 '표본평균 - 20'을 표준오차 단위로 나타낸 검정통계량이다.
# 양수이지만 0에 가깝다. sample estimates의 mean of x는 약 20.09이다.
# p-value 약 0.933 > 0.05이므로 H0를 기각하지 못한다.
# 이것은 평균이 정확히 20임을 입증한 결과가 아니다.

