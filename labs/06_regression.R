# Lab 06 — 단순·다중 선형회귀 출력 읽기 (약 25분)
# 이 파일만 위에서 아래로 실행하면 된다. mtcars의 연비를 설명하는 예제이다.

# 1. 목표 --------------------------------------------------------
# - summary(lm())에서 계수의 방향과 p-value를 찾아 해석한다.
# - 단순회귀와 다중회귀, R-squared와 adjusted R-squared를 구분한다.
# - 잔차를 관측값과 예측값의 차이로 읽고 간단한 진단 그림을 확인한다.

# 2. 핵심 개념과 작은 예제 ----------------------------------------
# 종속변수는 설명하려는 값, 독립변수는 그 값을 설명하는 데 사용하는 변수이다.
# 여기서는 종속변수 mpg(연비), 독립변수 wt(무게, 1,000 pounds)를 사용한다.
# 독립변수 하나이면 단순회귀, 둘 이상이면 다중회귀이다.
# lm(mpg ~ wt)는 연비를 '절편 + 무게의 계수 × 무게'로 설명하는 선형모형이다.
model_simple <- lm(mpg ~ wt, data = mtcars)
cat("단순회귀의 절편과 무게 계수:\n")
print(coef(model_simple))
# (Intercept) 약 37.29, wt 약 -5.34이므로 예측 연비는 37.29 - 5.34 × wt이다.
# 계수는 변수의 변화량과 연결된다. 단위가 없는 상관계수와 구분한다.
# wt = 0일 때의 절편은 식의 기준점이다. 관측 범위 밖인 무게 0의 자동차에
# 실제 연비가 37.29라고 해석하지 않는다.

# 3. 먼저 예상하기 -----------------------------------------------
# 예상 1: 위 모형에서 wt가 1 증가하면 예측 연비는 약 얼마만큼 변하는가?
# 예상 2: 관측 연비가 21, 예측 연비가 23이면 잔차(관측 - 예측)의 부호와 값은?
# 예상 3: hp(마력)를 추가하면 무게 계수가 반드시 -5.34로 유지될까?
#         독립변수를 추가할 때 R-squared와 adjusted R-squared는 모두
#         반드시 증가하는가? 4절의 비교표에서 확인한다.

# 4. 직접 실행 ----------------------------------------------------
# 실험 A: summary()에서 계수 표와 모형 전체의 적합도를 구분한다.
simple_summary <- summary(model_simple)
cat("단순회귀의 요약:\n")
print(simple_summary)

# Coefficients 표의 wt 행에서 다음 두 열을 찾는다.
# - Estimate 약 -5.34: 무게가 1(1,000 pounds) 증가할 때 예측 연비가 약 5.34 낮다.
# - Pr(>|t|): H0 'wt의 모집단 회귀계수 = 0'에 대한 양측검정의 p-value이다.
#   alpha = 0.05보다 작으므로, 모형의 가정 아래 H0를 기각한다.
# 별표 개수보다 p-value와 정한 유의수준을 직접 비교한다.
# 계수가 유의하다는 결과만으로 무게의 인과적 효과가 입증되지는 않는다.

# 아래쪽의 Multiple R-squared 약 0.753을 찾는다.
# 이 표본에서 연비 변동의 약 75.3%를 모형이 설명한다는 뜻이다.
# 예측이 75.3% 정확하다거나 자동차의 75.3%를 맞혔다는 뜻이 아니다.
# 출력 이름에 Multiple이 있어도 이 모형의 독립변수는 wt 하나이다.
# Adjusted R-squared 약 0.745는 변수 수와 표본 수를 고려해 조정한 값이다.

# 실험 B: 잔차를 원자료와 나란히 보며 부호를 해석한다.
# residuals()는 각 관측의 잔차, fitted()는 모형이 예측한 연비를 반환한다.
simple_residuals <- residuals(model_simple)
simple_fitted <- fitted(model_simple)
cat("처음 네 자동차의 관측, 예측, 잔차:\n")
print(data.frame(observed_mpg = mtcars$mpg[1:4],
                 fitted_mpg = simple_fitted[1:4],
                 residual = simple_residuals[1:4]))
# 첫 행: 관측 21 - 예측 약 23.28 = 잔차 약 -2.28이다.
# 잔차가 음수이면 모형이 실제보다 높게 예측했고, 양수이면 낮게 예측했다.
# 잔차가 0에 가까울수록 해당 관측의 예측값과 실제값이 가깝다.

# 진단 그림 하나로 예측값에 따라 잔차가 어떻게 퍼져 있는지 본다.
plot(simple_fitted, simple_residuals, main = "mpg ~ wt",
     xlab = "Fitted mpg", ylab = "Residual", pch = 19)
abline(h = 0, lty = 2, col = "gray40")
# 가로축은 예측 연비, 세로축은 잔차이다. 점선 위/아래가 양수/음수 잔차이다.
# 곡선 모양이나 예측값에 따라 퍼짐이 달라지는 패턴이 보이는지 살펴본다.
# 패턴은 모형 가정을 점검할 단서이다. 이 그림 하나로 모든 가정을 확정하지 않는다.

# 실험 C: 마력 hp를 추가하고 동일한 관측의 다중회귀와 비교한다.
# 이번 식은 '절편 + 무게 계수 × wt + 마력 계수 × hp'이다.
model_multiple <- lm(mpg ~ wt + hp, data = mtcars)
multiple_summary <- summary(model_multiple)
cat("다중회귀의 요약:\n")
print(multiple_summary)
# wt의 Estimate 약 -3.88: hp가 같을 때, 무게 1 증가에 대응하는 연비 감소량이다.
# hp의 Estimate 약 -0.032: wt가 같을 때, 마력 1 증가에 대응하는 연비 감소량이다.
# '다른 독립변수가 같을 때'라는 조건이 단순회귀와 다른 해석의 핵심이다.
# wt와 hp 행의 Pr(>|t|)를 각각 읽는다. 둘 다 0.05보다 작다.
# 각 검정의 H0는 다른 변수를 포함한 이 모형에서 해당 모집단 계수가 0이라는 것이다.

cat("같은 연비 자료에 대한 두 모형의 적합도 비교:\n")
print(data.frame(model = c("mpg ~ wt", "mpg ~ wt + hp"),
                 R_squared = c(simple_summary$r.squared,
                               multiple_summary$r.squared),
                 adjusted_R_squared = c(simple_summary$adj.r.squared,
                                        multiple_summary$adj.r.squared)))
# R-squared는 약 0.753 → 0.827, adjusted R-squared는 약 0.745 → 0.815이다.
# 같은 관측·종속변수의 절편 포함 최소제곱 회귀에서는 변수를 추가해도
# R-squared가 낮아지지 않는다. 이것만으로 추가 변수가 유용하다고 단정하지 않는다.
# Adjusted R-squared는 변수 추가를 고려하므로 낮아질 수도 있다.
# 이 예제에서는 조정한 값도 높아졌다. 이 표본의 적합도 개선으로 해석한다.

# 5. 결과 해석 ----------------------------------------------------
# 계수 표: 변수 행 → Estimate의 부호와 단위 → Pr(>|t|)와 alpha의 비교.
# 적합도: Multiple R-squared → 설명된 변동의 비율 → Adjusted R-squared와 비교.
# 잔차: 관측 - 예측 → 부호가 뜻하는 과대/과소 예측 → 그림의 패턴.
# 유의한 계수, 높은 적합도, 작은 개별 잔차는 서로 다른 정보를 준다.

# 6. 하나 바꿔보기 ------------------------------------------------
# 다중회귀에서 hp를 150으로 고정하고 wt만 2에서 3으로 바꾼다.
# 예상: 두 번째 자동차의 예측 연비는 첫 번째보다 약 얼마만큼 낮을까?
# predict()에는 예측하려는 독립변수 값을 작은 표로 전달한다.
new_cars <- data.frame(wt = c(2, 3), hp = c(150, 150))
cat("같은 마력에서 무게만 바꾼 예측:\n")
print(data.frame(new_cars, predicted_mpg = predict(model_multiple, newdata = new_cars)))
# 약 24.71 → 20.83으로 3.88 낮아진다. 다중회귀의 wt 계수와 대응한다.
# 두 값은 가상 조건에 대한 모형의 예측이다. 실제 관측이나 인과적 효과가 아니다.

